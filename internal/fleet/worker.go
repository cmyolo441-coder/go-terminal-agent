// Executor runs one task. It should honour ctx, which is canceled when the
// lease is revoked (the task was canceled or reassigned) or the worker's
// drain deadline passes. Because delivery is at-least-once, executors
// should make their side effects idempotent, keyed by Task.ID.
type Executor interface {
	Execute(ctx context.Context, a Assignment) (json.RawMessage, error)
}

// ExecutorFunc adapts a function to Executor.
type ExecutorFunc func(ctx context.Context, a Assignment) (json.RawMessage, error)

// Execute implements Executor.
func (f ExecutorFunc) Execute(ctx context.Context, a Assignment) (json.RawMessage, error) {
	return f(ctx, a)
}

type permanentError struct{ err error }

func (p permanentError) Error() string { return p.err.Error() }
func (p permanentError) Unwrap() error { return p.err }

// Permanent marks err as not worth retrying: the task is dead-lettered
// at once.
func Permanent(err error) error {
	if err == nil {
		return nil
	}
	return permanentError{err}
}

// IsPermanent reports whether err was marked with Permanent.
func IsPermanent(err error) bool {
	var p permanentError
	return errors.As(err, &p)
}

// WorkerConfig configures a Worker.
type WorkerConfig struct {
	// ID is stable for the machine; generated by the coordinator if empty.
	ID           string
	Capabilities Capabilities
	Version      string
	API          WorkerAPI
	Executor     Executor
	Clock        Clock
	Logger       *slog.Logger
	// HeartbeatInterval overrides the coordinator's suggestion.
	HeartbeatInterval time.Duration
	// PollWait is how long each lease request may long-poll (default 20s).
	PollWait time.Duration
	// DrainTimeout bounds how long shutdown waits for running tasks before
	// canceling them and releasing their leases (default 30s).
	DrainTimeout time.Duration
	// RetryMin and RetryMax bound the backoff after coordinator errors.
	RetryMin, RetryMax time.Duration
}

// WorkerStats counts what a worker did.
type WorkerStats struct {
	Leased    uint64
	Succeeded uint64
	Failed    uint64
	Revoked   uint64
	Released  uint64
	AckErrors uint64
}

// Worker leases tasks from a coordinator and runs them with an Executor,
// up to Capabilities.MaxConcurrency at a time.
type Worker struct {
	cfg         WorkerConfig
	log         *slog.Logger
	incarnation string

	mu       sync.Mutex
	id       string
	interval time.Duration
	running  map[string]*running // task ID -> run
	slots    chan struct{}
	killed   atomic.Bool
	kill     context.CancelFunc
	stats    struct{ leased, succeeded, failed, revoked, released, ackErrors atomic.Uint64 }
	wg       sync.WaitGroup
}

type running struct {
	a       Assignment
	cancel  context.CancelCauseFunc
	revoked atomic.Bool
}

var (
	errRevoked   = errors.New("fleet: lease revoked")
	errDrainTime = errors.New("fleet: drain timeout")
)

// NewWorker validates cfg.
func NewWorker(cfg WorkerConfig) (*Worker, error) {
	if cfg.API == nil || cfg.Executor == nil {
		return nil, fmt.Errorf("%w: worker needs an API and an executor", ErrInvalid)
	}
	if cfg.Capabilities.MaxConcurrency <= 0 {
		cfg.Capabilities.MaxConcurrency = 1
	}
	if cfg.Clock == nil {
		cfg.Clock = RealClock()
	}
	if cfg.Logger == nil {
		cfg.Logger = slog.New(slog.DiscardHandler)
	}
	if cfg.PollWait <= 0 {
		cfg.PollWait = 20 * time.Second
	}
	if cfg.DrainTimeout <= 0 {
		cfg.DrainTimeout = 30 * time.Second
	}
	if cfg.RetryMin <= 0 {
		cfg.RetryMin = 100 * time.Millisecond
	}
	if cfg.RetryMax < cfg.RetryMin {
		cfg.RetryMax = max(5*time.Second, cfg.RetryMin)
	}
	w := &Worker{
		cfg:         cfg,
		log:         cfg.Logger,
		incarnation: randHex(8),
		id:          cfg.ID,
		running:     map[string]*running{},
		slots:       make(chan struct{}, cfg.Capabilities.MaxConcurrency),
	}
	return w, nil
}

// ID returns the worker ID (known after registration).
func (w *Worker) ID() string {
	w.mu.Lock()
	defer w.mu.Unlock()
	return w.id
}

// Stats returns counters.
func (w *Worker) Stats() WorkerStats {
	return WorkerStats{
		Leased: w.stats.leased.Load(), Succeeded: w.stats.succeeded.Load(), Failed: w.stats.failed.Load(),
		Revoked: w.stats.revoked.Load(), Released: w.stats.released.Load(), AckErrors: w.stats.ackErrors.Load(),
	}
}

// Running returns the number of tasks in progress.
func (w *Worker) Running() int {
	w.mu.Lock()
	defer w.mu.Unlock()
	return len(w.running)
}

// Run registers, then leases and executes tasks until ctx ends. It then
// drains: it stops leasing, tells the coordinator, waits up to
// DrainTimeout for running tasks, releases whatever is left and
// deregisters.
func (w *Worker) Run(ctx context.Context) error {
	// work outlives ctx so running tasks can finish during the drain;
	// kill (tests) abandons everything like a crash.
	work, kill := context.WithCancel(context.WithoutCancel(ctx))
	w.mu.Lock()
	w.kill = kill
	w.mu.Unlock()
	defer kill()

	if err := w.register(ctx); err != nil {
		if w.killed.Load() {
			return errKilled
		}
		return err
	}
	hbCtx, stopHB := context.WithCancel(work)
	hbDone := make(chan struct{})
	go func() {
		defer close(hbDone)
		w.heartbeatLoop(hbCtx)
	}()

	w.pollLoop(ctx, work)

	if w.killed.Load() {
		stopHB()
		<-hbDone
		w.wg.Wait()
		return errKilled
	}
	w.drain(work)
	stopHB()
	<-hbDone
	return nil
}

var errKilled = errors.New("fleet: worker killed")

// crash simulates the process dying: everything stops with no further
// calls to the coordinator.
func (w *Worker) crash() {
	w.killed.Store(true)
	w.mu.Lock()
	k := w.kill
	runs := slices.Collect(maps.Values(w.running))
	w.mu.Unlock()
	for _, r := range runs {
		r.cancel(errKilled)
	}
	if k != nil {
		k()
	}
}

func (w *Worker) register(ctx context.Context) error {
	backoff := w.cfg.RetryMin
	for {
		w.mu.Lock()
		id := w.id
		w.mu.Unlock()
		resp, err := w.cfg.API.Register(ctx, RegisterRequest{
			WorkerID: id, Incarnation: w.incarnation, Capabilities: w.cfg.Capabilities, Version: w.cfg.Version,
		})
		if err == nil {
			w.mu.Lock()
			w.id = resp.WorkerID
			w.interval = resp.HeartbeatInterval.D()
			if w.cfg.HeartbeatInterval > 0 {
				w.interval = w.cfg.HeartbeatInterval
			}
			if w.interval <= 0 {
				w.interval = DefaultHeartbeatInterval
			}
			w.mu.Unlock()
			w.log.Info("fleet: worker registered", "worker", resp.WorkerID)
			return nil
		}
		if errors.Is(err, ErrInvalid) || errors.Is(err, ErrUnauthorized) || errors.Is(err, ErrForbidden) {
			return err
		}
		w.log.Warn("fleet: register failed; retrying", "err", err, "in", backoff)
		if err := sleepCtx(ctx, w.cfg.Clock, backoff); err != nil {
			return err
		}
		backoff = min(backoff*2, w.cfg.RetryMax)
	}
}

func (w *Worker) pollLoop(ctx, work context.Context) {
	backoff := w.cfg.RetryMin
	for ctx.Err() == nil && work.Err() == nil {
		// Wait for a free slot.
		select {
		case w.slots <- struct{}{}:
			<-w.slots
		case <-ctx.Done():
			return
		case <-work.Done():
			return
		}
		free := cap(w.slots) - len(w.slots)
		if free <= 0 {
			continue
		}
		resp, err := w.cfg.API.Lease(ctx, LeaseRequest{WorkerID: w.ID(), Max: free, Wait: Duration(w.cfg.PollWait)})
		if err != nil {
			if ctx.Err() != nil || work.Err() != nil {
				return
			}
			if errors.Is(err, ErrUnknownWorker) {
				if rerr := w.register(ctx); rerr != nil {
					return
				}
				continue
			}
			w.log.Warn("fleet: lease failed", "err", err, "retry_in", backoff)
			if sleepCtx(ctx, w.cfg.Clock, backoff) != nil {
				return
			}
			backoff = min(backoff*2, w.cfg.RetryMax)
			continue
		}
		backoff = w.cfg.RetryMin
		if len(resp.Assignments) == 0 {
			if resp.Draining || resp.Quarantined {
				d := min(max(resp.RetryAfter.D(), w.cfg.RetryMin), w.cfg.RetryMax)
				if sleepCtx(ctx, w.cfg.Clock, d) != nil {
					return
				}
			}
			continue
		}
		for _, a := range resp.Assignments {
			w.start(work, a)
		}
	}
}

func (w *Worker) start(work context.Context, a Assignment) {
	w.slots <- struct{}{}
	tctx, cancel := context.WithCancelCause(work)
	r := &running{a: a, cancel: cancel}
	w.mu.Lock()
	w.running[a.Task.ID] = r
	w.mu.Unlock()
	w.stats.leased.Add(1)
	w.wg.Add(1)
	go func() {
		defer w.wg.Done()
		defer func() { <-w.slots }()
		defer cancel(nil)
		w.execute(tctx, work, r)
		w.mu.Lock()
		if w.running[a.Task.ID] == r {
			delete(w.running, a.Task.ID)
		}
		w.mu.Unlock()
	}()
}

func (w *Worker) execute(tctx, work context.Context, r *running) {
	a := r.a
	res, err := w.safeExecute(tctx, a)
	if w.killed.Load() {
		return
	}
	cause := context.Cause(tctx)
	switch {
	case r.revoked.Load() || errors.Is(cause, errRevoked):
		w.stats.revoked.Add(1)
		return
	case errors.Is(cause, errDrainTime):
		w.ack(work, a, func(ctx context.Context) error {
			return w.cfg.API.Release(ctx, ReleaseRequest{WorkerID: w.ID(), TaskID: a.Task.ID, LeaseID: a.LeaseID})
		})
		w.stats.released.Add(1)
		return
	}
	if err == nil {
		if w.ack(work, a, func(ctx context.Context) error {
			return w.cfg.API.Complete(ctx, CompleteRequest{WorkerID: w.ID(), TaskID: a.Task.ID, LeaseID: a.LeaseID, Result: res})
		}) {
			w.stats.succeeded.Add(1)
		}
		return
	}
	var ra Duration
	var rae interface{ RetryAfter() time.Duration }
	if errors.As(err, &rae) {
		ra = Duration(rae.RetryAfter())
	}
	w.stats.failed.Add(1)
	w.ack(work, a, func(ctx context.Context) error {
		return w.cfg.API.Fail(ctx, FailRequest{
			WorkerID: w.ID(), TaskID: a.Task.ID, LeaseID: a.LeaseID,
			Error: err.Error(), Permanent: IsPermanent(err), RetryAfter: ra,
		})
	})
}

// safeExecute turns an executor panic into a permanent failure.
func (w *Worker) safeExecute(ctx context.Context, a Assignment) (res json.RawMessage, err error) {
	defer func() {
		if p := recover(); p != nil {
			err = Permanent(fmt.Errorf("executor panic: %v", p))
		}
	}()
	return w.cfg.Executor.Execute(ctx, a)
}

// ack sends an acknowledgement, retrying transient errors until the lease
// would have expired anyway. It reports whether the coordinator accepted.
func (w *Worker) ack(work context.Context, a Assignment, call func(context.Context) error) bool {
	backoff := w.cfg.RetryMin
	deadline := w.cfg.Clock.Now().Add(max(a.Task.LeaseTimeout.D(), 5*time.Second))
	for {
		if w.killed.Load() {
			return false
		}
		err := call(work)
		if err == nil {
			return true
		}
		if errors.Is(err, ErrLeaseLost) || errors.Is(err, ErrNotFound) || errors.Is(err, ErrInvalid) ||
			errors.Is(err, ErrForbidden) || errors.Is(err, ErrUnauthorized) {
			w.stats.ackErrors.Add(1)
			w.log.Warn("fleet: acknowledgement refused", "task", a.Task.ID, "err", err)
			return false
		}
		if !w.cfg.Clock.Now().Before(deadline) || work.Err() != nil {
			w.stats.ackErrors.Add(1)
			w.log.Warn("fleet: acknowledgement abandoned", "task", a.Task.ID, "err", err)
			return false
		}
		if sleepCtx(work, w.cfg.Clock, backoff) != nil {
			return false
		}
		backoff = min(backoff*2, w.cfg.RetryMax)
	}
}

func (w *Worker) heartbeatLoop(ctx context.Context) {
	for {
		w.mu.Lock()
		iv := w.interval
		w.mu.Unlock()
		if sleepCtx(ctx, w.cfg.Clock, iv) != nil {
			return
		}
		w.heartbeat(ctx)
	}
}

func (w *Worker) heartbeat(ctx context.Context) {
	w.mu.Lock()
	refs := make([]LeaseRef, 0, len(w.running))
	for _, r := range w.running {
		refs = append(refs, LeaseRef{TaskID: r.a.Task.ID, LeaseID: r.a.LeaseID})
	}
	id := w.id
	w.mu.Unlock()
	resp, err := w.cfg.API.Heartbeat(ctx, HeartbeatRequest{WorkerID: id, Leases: refs})
	if err != nil {
		if errors.Is(err, ErrUnknownWorker) && ctx.Err() == nil {
			// The coordinator forgot us (failover, or we were declared
			// lost): register again and keep our leases if still valid.
			if rerr := w.register(ctx); rerr == nil {
				w.heartbeat(ctx)
			}
			return
		}
		if ctx.Err() == nil {
			w.log.Warn("fleet: heartbeat failed", "err", err)
		}
		return
	}
	for _, ref := range resp.Revoked {
		w.mu.Lock()
		r := w.running[ref.TaskID]
		w.mu.Unlock()
		if r != nil && r.a.LeaseID == ref.LeaseID {
			r.revoked.Store(true)
			r.cancel(errRevoked)
		}
	}
}

func (w *Worker) drain(work context.Context) {
	id := w.ID()
	dctx, cancel := context.WithTimeout(work, 5*time.Second)
	if err := w.cfg.API.Drain(dctx, id); err != nil {
		w.log.Warn("fleet: drain request failed", "err", err)
	}
	cancel()
	done := make(chan struct{})
	go func() {
		w.wg.Wait()
		close(done)
	}()
	t := w.cfg.Clock.NewTimer(w.cfg.DrainTimeout)
	select {
	case <-done:
		t.Stop()
	case <-t.C():
		w.mu.Lock()
		runs := slices.Collect(maps.Values(w.running))
		w.mu.Unlock()
		for _, r := range runs {
			r.cancel(errDrainTime)
		}
		<-done
	}
	dctx, cancel = context.WithTimeout(work, 5*time.Second)
	defer cancel()
	if err := w.cfg.API.Deregister(dctx, id); err != nil {
		w.log.Warn("fleet: deregister failed", "err", err)
	}
}
