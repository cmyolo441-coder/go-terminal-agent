// Skip reasons recorded in Stats.
const (
	SkipIgnored   = "ignored"
	SkipBinary    = "binary"
	SkipGenerated = "generated"
	SkipTooLarge  = "too-large"
	SkipSymlink   = "symlink"
	SkipVendored  = "vendored"
	SkipError     = "error"
	SkipLimit     = "file-limit"
	SkipExcluded  = "excluded"
)

