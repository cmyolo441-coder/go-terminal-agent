func TestConcurrentQueriesDuringRefresh(t *testing.T) {
	root := t.TempDir()
	files := map[string]string{}
	for i := 0; i < 60; i++ {
		files[fmt.Sprintf("pkg%d/file%d.go", i%6, i)] = fmt.Sprintf("package p\n\n// Handler%d serves requests.\nfunc Handler%d() int { return %d }\n", i, i, i)
	}
	writeTree(t, root, files)
	ix := openIndex(t, root, func(o *Options) { o.RefreshInterval = -1 })
	ctx := context.Background()
	var wg sync.WaitGroup
	errs := make(chan error, 100)
	for w := 0; w < 8; w++ {
		wg.Add(1)
		go func(w int) {
			defer wg.Done()
			for i := 0; i < 10; i++ {
				switch (w + i) % 4 {
				case 0:
					if _, err := ix.Search(ctx, "serves requests handler", SearchOptions{}); err != nil {
						errs <- err
					}
				case 1:
					if _, err := ix.Symbols(ctx, SymbolQuery{Name: "Handler"}); err != nil {
						errs <- err
					}
				case 2:
					if _, err := ix.RepoMap(ctx, RepoMapOptions{Budget: 500}); err != nil {
						errs <- err
					}
				case 3:
					p := filepath.Join(root, fmt.Sprintf("pkg%d/file%d.go", w%6, w))
					touchPast(t, p, fmt.Sprintf("package p\n\nfunc Handler%d() int { return %d }\n", w, i), time.Duration(i+1)*time.Minute)
					ix.Invalidate(p)
				}
			}
		}(w)
	}
	wg.Wait()
	close(errs)
	for err := range errs {
		t.Error(err)
	}
}

func TestLargeRepository(t *testing.T) {
	if testing.Short() {
		t.Skip("large repository test skipped in -short mode")
	}
	root := t.TempDir()
	files := map[string]string{}
	const n = 3000
	for i := 0; i < n; i++ {
		files[fmt.Sprintf("svc%02d/mod%03d/file%d.go", i%40, i%97, i)] = fmt.Sprintf(
			"package mod\n\n// ComputeThing%d computes thing number %d for the ledger.\nfunc ComputeThing%d(x int) int {\n\treturn x * %d\n}\n\ntype Record%d struct{ ID int }\n", i, i, i, i, i)
	}
	files["core/ledger.go"] = "package core\n\n// ReconcileLedger balances the ledger accounts at end of day.\nfunc ReconcileLedger() error { return nil }\n"
	writeTree(t, root, files)
	ix := openIndex(t, root, func(o *Options) { o.CacheDir = t.TempDir() })
	start := time.Now()
	st := mustRefresh(t, ix)
	if st.Files != n+1 || st.Symbols < 2*n {
		t.Fatalf("stats = %+v", st)
	}
	t.Logf("indexed %d files, %d symbols, %d chunks in %v", st.Files, st.Symbols, st.Chunks, time.Since(start))
	hits, err := ix.Search(context.Background(), "balance ledger accounts end of day", SearchOptions{Limit: 3})
	if err != nil || len(hits) == 0 || hits[0].Path != "core/ledger.go" {
		t.Fatalf("hits = %+v err = %v", hits, err)
	}
	// Warm start from the cache re-reads nothing.
	ix2 := openIndex(t, root, func(o *Options) { o.CacheDir = ix.opts.CacheDir })
	if s := ix2.Stats(); !s.FromCache || s.Files != n+1 {
		t.Fatalf("cache not loaded: %+v", s)
	}
	st2 := mustRefresh(t, ix2)
	if st2.Parsed != 0 || st2.Reused != n+1 {
		t.Fatalf("warm refresh: %+v", st2)
	}
}
