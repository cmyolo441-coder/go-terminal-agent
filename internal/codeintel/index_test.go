func TestIncrementalRefresh(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"a.go": "package p\n\nfunc Alpha() {}\n",
		"b.go": "package p\n\nfunc Beta() {}\n",
		"c.go": "package p\n\nfunc Gamma() {}\n",
	})
	ix := openIndex(t, root, nil)
	st := mustRefresh(t, ix)
	if st.Parsed != 3 || st.Reused != 0 {
		t.Fatalf("first refresh: %+v", st)
	}
	st = mustRefresh(t, ix)
	if st.Parsed != 0 || st.Reused != 3 || st.Removed != 0 {
		t.Fatalf("no-op refresh: %+v", st)
	}
	touchPast(t, filepath.Join(root, "b.go"), "package p\n\nfunc BetaRenamed() {}\n", 30*time.Minute)
	if err := os.Remove(filepath.Join(root, "c.go")); err != nil {
		t.Fatal(err)
	}
	writeTree(t, root, map[string]string{"d.go": "package p\n\nfunc Delta() {}\n"})
	st = mustRefresh(t, ix)
	if st.Parsed != 2 || st.Reused != 1 || st.Removed != 1 || st.Files != 3 {
		t.Fatalf("incremental refresh: %+v", st)
	}
	ms, err := ix.Symbols(context.Background(), SymbolQuery{Name: "BetaRenamed"})
	if err != nil || len(ms) != 1 {
		t.Fatalf("renamed symbol not found: %v %v", ms, err)
	}
	if ms, _ := ix.Symbols(context.Background(), SymbolQuery{Name: "Gamma"}); len(ms) != 0 {
		t.Fatalf("deleted symbol still indexed: %v", ms)
	}
}

func TestRacyFilesAreReread(t *testing.T) {
	root := t.TempDir()
	abs := filepath.Join(root, "r.go")
	if err := os.WriteFile(abs, []byte("package p\nfunc One() {}\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	ix := openIndex(t, root, nil)
	mustRefresh(t, ix)
	st, _ := os.Stat(abs)
	mtime := st.ModTime()
	// Same size, same mtime, different content: only racy handling
	// catches this.
	if err := os.WriteFile(abs, []byte("package p\nfunc Two() {}\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.Chtimes(abs, mtime, mtime); err != nil {
		t.Fatal(err)
	}
	mustRefresh(t, ix)
	if ms, _ := ix.Symbols(context.Background(), SymbolQuery{Name: "Two"}); len(ms) != 1 {
		t.Fatalf("racy edit missed: %v", ms)
	}
}

func TestInvalidateRefreshesOnlyNamedFiles(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"a.go": "package p\n\nfunc Alpha() {}\n",
		"b.go": "package p\n\nfunc Beta() {}\n",
	})
	ix := openIndex(t, root, nil) // one-hour refresh interval
	mustRefresh(t, ix)
	ctx := context.Background()

	touchPast(t, filepath.Join(root, "a.go"), "package p\n\nfunc AlphaNew() {}\n", 10*time.Minute)
	writeTree(t, root, map[string]string{"new.go": "package p\n\nfunc Fresh() {}\n", "c.go": "package p\n\nfunc Unnoticed() {}\n"})
	// Not invalidated yet: the stale index is served.
	if ms, _ := ix.Symbols(ctx, SymbolQuery{Name: "AlphaNew"}); len(ms) != 0 {
		t.Fatal("index refreshed without being asked")
	}
	ix.Invalidate(filepath.Join(root, "a.go"), "new.go", "/elsewhere/x.go", "")
	if ms, _ := ix.Symbols(ctx, SymbolQuery{Name: "AlphaNew"}); len(ms) != 1 {
		t.Fatalf("invalidated edit not picked up: %v", ms)
	}
	if ms, _ := ix.Symbols(ctx, SymbolQuery{Name: "Fresh"}); len(ms) != 1 {
		t.Fatal("invalidated new file not indexed")
	}
	if ms, _ := ix.Symbols(ctx, SymbolQuery{Name: "Unnoticed"}); len(ms) != 0 {
		t.Fatal("targeted refresh scanned files it was not told about")
	}
	// Deleting and invalidating removes the file.
	os.Remove(filepath.Join(root, "b.go"))
	ix.Invalidate("b.go")
	if ms, _ := ix.Symbols(ctx, SymbolQuery{Name: "Beta"}); len(ms) != 0 {
		t.Fatal("deleted file still indexed")
	}
	// An invalidated path that is ignored is not indexed.
	writeTree(t, root, map[string]string{".gitignore": "secret.go\n", "secret.go": "package p\nfunc Hidden() {}\n"})
	ix.Invalidate("secret.go")
	if ms, _ := ix.Symbols(ctx, SymbolQuery{Name: "Hidden"}); len(ms) != 0 {
		t.Fatal("ignored file indexed through Invalidate")
	}
}

