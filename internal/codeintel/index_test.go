func TestRefreshCancellationKeepsPreviousSnapshot(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{"a.go": "package p\nfunc A() {}\n"})
	ix := openIndex(t, root, nil)
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	if _, err := ix.Refresh(ctx); !errors.Is(err, context.Canceled) {
		t.Fatalf("err = %v", err)
	}
	if ix.Stats().Files != 0 {
		t.Fatal("cancelled refresh published a snapshot")
	}
	mustRefresh(t, ix)
	writeTree(t, root, map[string]string{"b.go": "package p\nfunc B() {}\n"})
	ix.Invalidate("b.go")
	if _, err := ix.Refresh(ctx); !errors.Is(err, context.Canceled) {
		t.Fatalf("err = %v", err)
	}
	if ix.Stats().Files != 1 {
		t.Fatal("cancelled refresh replaced the snapshot")
	}
	// The invalidation survives the cancelled refresh.
	ix.mu.Lock()
	pending := ix.pending["b.go"]
	ix.mu.Unlock()
	if !pending {
		t.Fatal("pending invalidation lost on cancellation")
	}
}

