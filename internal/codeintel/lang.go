// generatedNames are files that are generated or lock files; their content
// adds noise to search without being code anyone edits.
var generatedNames = setOf(
	"package-lock.json", "yarn.lock", "pnpm-lock.yaml", "Cargo.lock", "go.sum", "poetry.lock",
	"Gemfile.lock", "composer.lock", "Pipfile.lock", "uv.lock", "bun.lock", "flake.lock",
	"npm-shrinkwrap.json", "mix.lock", "pubspec.lock", "Podfile.lock", "packages.lock.json",
)

// isGeneratedName reports whether a file name follows a generated-file
// naming convention.
func isGeneratedName(name string) bool {
	if generatedNames[name] {
		return true
	}
	lower := strings.ToLower(name)
	for _, suf := range []string{
		".min.js", ".min.css", ".min.mjs", ".js.map", ".css.map", ".map", ".pb.go", ".pb.gw.go",
		"_pb2.py", "_pb2_grpc.py", ".pb.h", ".pb.cc", ".g.dart", ".freezed.dart", ".designer.cs",
		"_generated.go", ".gen.go", "_string.go.golden", ".bundle.js", ".chunk.js",
	} {
		if strings.HasSuffix(lower, suf) {
			return true
		}
	}
	return strings.Contains(lower, ".generated.")
}

// isGeneratedContent looks for the standard "generated" markers in the head
// of a file: Go's "Code generated ... DO NOT EDIT." and the @generated tag.
func isGeneratedContent(head []byte) bool {
	if len(head) > 2048 {
		head = head[:2048]
	}
	s := string(head)
	if strings.Contains(s, "@generated") && !strings.Contains(s, "@generated by") {
		return true
	}
	if i := strings.Index(s, "Code generated "); i >= 0 && strings.Contains(s[i:], "DO NOT EDIT") {
		return true
	}
	if strings.Contains(s, "AUTO-GENERATED FILE") || strings.Contains(s, "autogenerated file - do not edit") {
		return true
	}
	return false
}

// lexSpec describes the comment and string syntax of a language.
type lexSpec struct {
	lineComments  []string
	blockComments [][2]string
	quotes        string
	// charLiterals: a single quote opens a character literal (C, Java,
	// Rust) rather than a string. Rust lifetimes ('a) are recognised.
	charLiterals bool
	tripleQuotes bool // Python """ and '''
	templates    bool // JS/TS `${}` template literals
	regexLits    bool // JS/TS /regex/ literals
	rustRaw      bool // Rust r#"..."# raw strings
	// rawBacktick: backquoted strings take no escapes (Go raw strings).
	rawBacktick bool
}

